import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

// Diff src/schema.ts against the last snapshot and write the next migration (pass `--name x`, or
// `--custom --name x` for hand-written SQL). New tables also need FORCE ROW LEVEL SECURITY there.
execFileSync("pnpm", ["exec", "drizzle-kit", "generate", ...process.argv.slice(2)], {
  stdio: "inherit",
});
const migrations = new URL("../migrations/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", migrations), "utf8")) as {
  entries: { tag: string }[];
};
// The full current schema, for fresh test databases and review; never applied to a live database.
writeFileSync(
  new URL("../sql/schema.sql", import.meta.url),
  "-- Generated by `pnpm --filter @btc-lightning-pay/db generate` from migrations/; do not edit.\n" +
    journal.entries
      .map((entry) =>
        readFileSync(new URL(`${entry.tag}.sql`, migrations), "utf8").replaceAll(
          "--> statement-breakpoint",
          "",
        ),
      )
      .join("\n"),
);
